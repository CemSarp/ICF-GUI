//! The reviewed batch wrapper. Pure text generation; every user value is either restricted to a
//! conservative charset (paths, names) or single-quoted (arguments, environment values).
//!
//! Life of a run on the compute node (markers `@@icfcc <time> <EVENT> ...` go to stdout and to
//! `<run dir>/icfcc-status.log`, which the app reads with a bounded `tail`):
//!   ALLOCATED → STAGE ENV → STAGE STAGING (private scratch, archives validated then extracted)
//!   → STAGE TRAINING (+ periodic SAVING_CHECKPOINTS) → STAGE COPYING_RESULTS → CLEANUP → DONE.
//! An EXIT trap always attempts copy-back and cleanup; USR1 (time limit near) and TERM (scancel)
//! are forwarded to the program first. Nothing survives a node failure except what was synced.

use super::{split_placeholders, CheckpointMode, HfCache, ScratchRoot, Toolchain, WorkflowConfig, WorkflowKind};
use crate::jobs::request::{format_time_limit, shell_quote as q};

/// Delimiters of the heredocs embedded in the job script; validated against content at submit.
pub fn stager_delimiter(tag: &str) -> String {
    format!("ICFCC_STAGER_{tag}")
}
pub fn smoke_delimiter(tag: &str) -> String {
    format!("ICFCC_SMOKE_{tag}")
}

fn render_arg(a: &str) -> String {
    match split_placeholders(a) {
        Ok(parts) => parts.iter().map(|(var, s)| if *var { format!("\"${s}\"") } else { q(s) }).collect(),
        Err(_) => q(a), // unreachable after validation; stays literal
    }
}

/// Shell lines that load the CUDA toolchain; `fail` is the caller's failure command prefix
/// (it gets one reason word). Shared with the interactive kernel step (ADR-031).
pub(crate) fn toolchain_lines(t: &Toolchain, fail: &str) -> String {
    let mut s = String::new();
    match t {
        Toolchain::None => {}
        Toolchain::Rc { path } => s += &format!("[ -r {p} ] || {fail} toolchain_missing\nsource {p} || {fail} toolchain_failed\n", p = q(path)),
        Toolchain::Modules { names } => {
            s += "if ! command -v module >/dev/null 2>&1; then for f in /etc/profile.d/lmod.sh /etc/profile.d/modules.sh; do if [ -r \"$f\" ]; then . \"$f\"; break; fi; done; fi\n";
            s += &format!("command -v module >/dev/null 2>&1 || {fail} module_command_missing\n");
            s += &format!("module load {} || {fail} module_load_failed\n", names.iter().map(|n| q(n)).collect::<Vec<_>>().join(" "));
        }
    }
    s
}

