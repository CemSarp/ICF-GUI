//! "Sign VS Code in through this app" (ADR-028): VS Code's own `ssh` reuses the app's already
//! authenticated OpenSSH master through its control socket, so it never asks for a password.
//! No secret leaves the app: the socket is only reachable by the same macOS user (private temp
//! dir), and VS Code is pointed at it by an app-managed ssh config chosen through VS Code's
//! `remote.SSH.configFile` setting — `~/.ssh/config` is never modified.
//!
//! Lifetime: the shared connection lives as long as the app's master. Without it (app closed or
//! disconnected) the link dangles and ssh falls back to a normal, prompted login.

use crate::commands::AppState;
use crate::errors::{AppError, AppResult, ErrorCode};
use crate::integrations::vscode::merge_key;
use crate::ssh::Hop;
use crate::util::{now_ms, random_hex};
use serde::Serialize;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::sync::atomic::Ordering;
use tauri::State;

pub const CONFIG_KEY: &str = "remote.SSH.configFile";
const PREVIEW_TTL_MS: u64 = 10 * 60_000;

/// Stable name for the control socket VS Code connects to; recreated on every connect. Not
/// `icfcc-*`, so the stale-session sweep (which removes `icfcc-*` directories) never touches it.
pub fn link_path() -> PathBuf {
    std::env::temp_dir().join("icfcc_vscode.sock")
}

pub fn config_path(config_dir: &Path) -> PathBuf {
    config_dir.join("vscode_ssh_config")
}

pub fn settings_path(home: &Path) -> PathBuf {
    home.join("Library/Application Support/Code/User/settings.json")
}

pub fn share_alias(alias: &str) -> String {
    format!("icfcc-{alias}")
}

fn valid_user(u: &str) -> bool {
    !u.is_empty() && u.len() <= 64 && !u.starts_with('-') && u.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
}

fn hop_spec(h: &Hop) -> AppResult<String> {
    crate::profiles::validate_host(&h.hostname).map_err(|m| AppError::invalid(format!("Host name {m}.")))?;
    let user = if h.user.is_empty() {
        String::new()
    } else if valid_user(&h.user) {
        format!("{}@", h.user)
    } else {
        return Err(AppError::invalid("A user name in the SSH route has unsupported characters."));
    };
    Ok(if h.port == 22 || h.port == 0 { format!("{user}{}", h.hostname) } else { format!("{user}{}:{}", h.hostname, h.port) })
}

/// The app-managed ssh config VS Code reads. Its own block comes first (first value wins in
/// ssh_config), then everything from the user's config, so other hosts keep working unchanged.
pub fn managed_config(alias: &str, hops: &[Hop], uses_proxy_command: bool, link: &Path, user_config: &Path) -> AppResult<String> {
    crate::profiles::validate_host(alias).map_err(|m| AppError::invalid(format!("SSH alias {m}.")))?;
    let dest = hops.last().ok_or_else(|| AppError::internal("The SSH route is unknown; connect first."))?;
    crate::profiles::validate_host(&dest.hostname).map_err(|m| AppError::invalid(format!("Host name {m}.")))?;
    for p in [link, user_config] {
        let s = p.to_string_lossy();
        if s.contains('"') || s.chars().any(char::is_control) {
            return Err(AppError::internal("Unsupported characters in a local path."));
        }
    }
    let mut s = String::from(
        "# Managed by ICF Control Center: VS Code reuses the app's signed-in connection.\n\
         # Turn it off in the app (Projects → VS Code); do not edit this file by hand.\n",
    );
    s += &format!("Host {}\n", share_alias(alias));
    s += &format!("    HostName {}\n", dest.hostname);
    if valid_user(&dest.user) {
        s += &format!("    User {}\n", dest.user);
    }
    if dest.port != 22 && dest.port != 0 {
        s += &format!("    Port {}\n", dest.port);
    }
    let jumps = &hops[..hops.len() - 1];
    if !jumps.is_empty() && !uses_proxy_command {
        let spec = jumps.iter().map(hop_spec).collect::<AppResult<Vec<_>>>()?.join(",");
        s += &format!("    ProxyJump {spec}\n");
    }
    s += "    ControlMaster no\n";
    s += &format!("    ControlPath \"{}\"\n", link.display());
    s += &format!("\nHost *\n    Include \"{}\"\n", user_config.display());
    Ok(s)
}

/// Point the stable link at the current master's socket, or remove it. Only ever replaces a
/// symlink; a regular file at that path is left alone (and sharing simply does not work).
pub fn update_link(ctl: Option<&Path>) {
    let link = link_path();
    if std::fs::symlink_metadata(&link).is_ok_and(|m| m.file_type().is_symlink()) {
        let _ = std::fs::remove_file(&link);
    }
    if let Some(ctl) = ctl {
        let _ = std::os::unix::fs::symlink(ctl, &link);
    }
}

fn link_target() -> Option<PathBuf> {
    std::fs::read_link(link_path()).ok()
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ShareStatus {
    pub enabled: bool,
    /// Host name VS Code opens (`icfcc-<alias>`) when sharing is on.
    pub alias: Option<String>,
    /// The link points at the live master: VS Code will not be asked for a password.
    pub active: bool,
    /// VS Code was opened through the shared connection since this connect.
    pub in_use: bool,
    pub config_file: String,
    pub settings_file: String,
}

async fn status_of(state: &AppState) -> ShareStatus {
    let enabled = state.projects.lock().unwrap().data.vscode_share;
    let session = state.session.lock().await.clone();
    let active = match &session {
        Some(s) if enabled => link_target().as_deref() == Some(s.ctl.as_path()) && s.ctl.exists(),
        _ => false,
    };
    ShareStatus {
        enabled,
        alias: session.filter(|_| enabled).map(|s| share_alias(&s.profile.ssh_alias)),
        active,
        in_use: active && state.vscode_in_use.load(Ordering::Relaxed),
        config_file: config_path(&state.config_dir).display().to_string(),
        settings_file: settings_path(&state.env.home).display().to_string(),
    }
}

#[tauri::command]
pub async fn vscode_share_status(state: State<'_, AppState>) -> AppResult<ShareStatus> {
    Ok(status_of(&state).await)
}

pub struct StoredShare {
    settings_sha: Option<String>,
    settings_after: String,
    config_text: String,
    created_ms: u64,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SharePreview {
    /// Present only when the change can be applied automatically.
    pub preview_id: Option<String>,
    pub alias: String,
    pub settings_file: String,
    pub settings_before: Option<String>,
    pub settings_after: Option<String>,
    pub config_file: String,
    pub config_text: String,
    /// Why settings.json cannot be edited automatically (e.g. it contains comments).
    pub problem: Option<String>,
    pub manual_snippet: String,
}

fn sha(bytes: &[u8]) -> String {
    let mut h = crate::transfers::sha256::Sha256::default();
    h.update(bytes);
    h.hex()
}

fn read_settings(path: &Path) -> AppResult<Option<String>> {
    match std::fs::read(path) {
        Ok(b) => String::from_utf8(b).map(Some).map_err(|_| AppError::invalid("VS Code's settings.json is not UTF-8 text.")),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(_) => Err(AppError::new(ErrorCode::Internal, "Could not read VS Code's settings.json.")),
    }
}

#[tauri::command]
pub async fn vscode_share_preview(state: State<'_, AppState>) -> AppResult<SharePreview> {
    let session =
        state.session.lock().await.clone().ok_or_else(|| AppError::new(ErrorCode::NotConnected, "Connect first: VS Code reuses the app's connection."))?;
    let config_file = config_path(&state.config_dir);
    let user_config = state.env.home.join(".ssh/config");
    let config_text = managed_config(&session.profile.ssh_alias, &session.resolved.hops, session.resolved.uses_proxy_command, &link_path(), &user_config)?;
    let settings_file = settings_path(&state.env.home);
    let before = read_settings(&settings_file)?;
    let value = config_file.display().to_string();
    let manual_snippet = format!("\"{CONFIG_KEY}\": {}", serde_json::Value::String(value.clone()));
    let merged = merge_key(before.as_deref(), CONFIG_KEY, Some(serde_json::Value::String(value)));
    let (preview_id, after, problem) = match merged {
        Ok(after) => {
            let id = random_hex(8);
            let mut previews = state.share_previews.lock().unwrap();
            previews.retain(|_, p| now_ms().saturating_sub(p.created_ms) < PREVIEW_TTL_MS);
            previews.insert(
                id.clone(),
                StoredShare {
                    settings_sha: before.as_deref().map(|b| sha(b.as_bytes())),
                    settings_after: after.clone(),
                    config_text: config_text.clone(),
                    created_ms: now_ms(),
                },
            );
            (Some(id), Some(after), None)
        }
        Err(e) => (None, None, Some(e)),
    };
    Ok(SharePreview {
        preview_id,
        alias: share_alias(&session.profile.ssh_alias),
        settings_file: settings_file.display().to_string(),
        settings_before: before,
        settings_after: after,
        config_file: config_file.display().to_string(),
        config_text,
        problem,
        manual_snippet,
    })
}

/// Write `content` next to `path` and rename it into place (same folder, so the rename is atomic).
fn replace_file(path: &Path, content: &str, mode: u32) -> AppResult<()> {
    let dir = path.parent().ok_or_else(|| AppError::internal("Bad settings path"))?;
    std::fs::create_dir_all(dir).map_err(|_| AppError::internal("Could not create the folder for the file."))?;
    let tmp = dir.join(format!(".{}.icfcc-{}", path.file_name().unwrap_or_default().to_string_lossy(), random_hex(4)));
    let res = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(mode)
        .open(&tmp)
        .and_then(|mut f| std::io::Write::write_all(&mut f, content.as_bytes()))
        .and_then(|_| std::fs::rename(&tmp, path));
    if res.is_err() {
        let _ = std::fs::remove_file(&tmp);
        return Err(AppError::internal("Could not write the file."));
    }
    Ok(())
}

/// Copy the current settings.json aside before changing it (never overwrites an earlier backup).
fn backup(path: &Path) -> AppResult<()> {
    if !path.exists() {
        return Ok(());
    }
    let b = path.with_file_name(format!("settings.json.icfcc-backup-{}", now_ms()));
    std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&b)
        .and_then(|mut f| std::io::Write::write_all(&mut f, &std::fs::read(path)?))
        .map_err(|_| AppError::internal("Could not back up VS Code's settings.json, so nothing was changed."))
}

#[tauri::command]
pub async fn vscode_share_apply(state: State<'_, AppState>, preview_id: String) -> AppResult<ShareStatus> {
    let p = state
        .share_previews
        .lock()
        .unwrap()
        .remove(&preview_id)
        .filter(|p| now_ms().saturating_sub(p.created_ms) < PREVIEW_TTL_MS)
        .ok_or_else(|| AppError::invalid("This preview has expired. Open it again."))?;
    let settings_file = settings_path(&state.env.home);
    let now = read_settings(&settings_file)?;
    if now.as_deref().map(|b| sha(b.as_bytes())) != p.settings_sha {
        return Err(AppError::new(ErrorCode::Conflict, "VS Code's settings.json changed since the preview. Nothing was written; try again."));
    }
    replace_file(&config_path(&state.config_dir), &p.config_text, 0o600)?;
    backup(&settings_file)?;
    replace_file(&settings_file, &p.settings_after, 0o644)?;
    {
        let mut store = state.projects.lock().unwrap();
        store.data.vscode_share = true;
        store.save()?;
    }
    if let Some(s) = state.session.lock().await.as_ref() {
        update_link(Some(&s.ctl));
    }
    Ok(status_of(&state).await)
}

/// Undo: remove our setting (only if it still points at our file), our config and the link.
#[tauri::command]
pub async fn vscode_share_disable(state: State<'_, AppState>) -> AppResult<ShareStatus> {
    let settings_file = settings_path(&state.env.home);
    let ours = config_path(&state.config_dir).display().to_string();
    if let Some(text) = read_settings(&settings_file)? {
        let points_at_ours = serde_json::from_str::<serde_json::Value>(text.trim_start_matches('\u{feff}'))
            .ok()
            .and_then(|v| v.get(CONFIG_KEY).and_then(|x| x.as_str()).map(|x| x == ours));
        match points_at_ours {
            Some(true) => {
                let after = merge_key(Some(&text), CONFIG_KEY, None).map_err(AppError::invalid)?;
                backup(&settings_file)?;
                replace_file(&settings_file, &after, 0o644)?;
            }
            None if text.contains(&ours) => {
                return Err(AppError::invalid(format!(
                    "VS Code's settings.json has comments, so the app cannot edit it. Remove the line \"{CONFIG_KEY}\" from it in VS Code, then turn sharing off again."
                )))
            }
            _ => {}
        }
    }
    let _ = std::fs::remove_file(config_path(&state.config_dir));
    update_link(None);
    state.vscode_in_use.store(false, Ordering::Relaxed);
    {
        let mut store = state.projects.lock().unwrap();
        store.data.vscode_share = false;
        store.save()?;
    }
    Ok(status_of(&state).await)
}

/// Connect/disconnect hooks: keep the link in step with the app's master while sharing is on.
pub fn on_connected(state: &AppState, ctl: &Path) {
    state.vscode_in_use.store(false, Ordering::Relaxed);
    if state.projects.lock().unwrap().data.vscode_share {
        update_link(Some(ctl));
    }
}

pub fn on_closed(state: &AppState) {
    state.vscode_in_use.store(false, Ordering::Relaxed);
    if link_target().is_some() {
        update_link(None);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    fn hop(user: &str, host: &str, port: u16) -> Hop {
        Hop { alias: host.into(), user: user.into(), hostname: host.into(), port }
    }

    fn ssh_g(cfg: &Path, host: &str) -> String {
        let out = Command::new("/usr/bin/ssh").arg("-G").arg("-F").arg(cfg).arg("--").arg(host).env_clear().output().unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
        String::from_utf8(out.stdout).unwrap()
    }
    fn g<'a>(out: &'a str, key: &str) -> Option<&'a str> {
        out.lines().find_map(|l| l.strip_prefix(key).and_then(|r| r.strip_prefix(' ')))
    }

    #[test]
    fn managed_config_routes_our_alias_to_the_socket_and_keeps_every_other_host() {
        let dir = std::env::temp_dir().join(format!("icfcc-share-{}", random_hex(4)));
        std::fs::create_dir_all(&dir).unwrap();
        let user_cfg = dir.join("user_config");
        // A user config with its own wildcard ControlPath: our block must still win for our alias.
        std::fs::write(&user_cfg, "Host other\n    HostName other.example\n    User bob\n\nHost *\n    ControlMaster auto\n    ControlPath /tmp/user-%r@%h\n")
            .unwrap();
        let link = dir.join("vscode.sock");
        let hops = [hop("s1", "gw.example", 2222), hop("s1234567", "hastings.inf.ed.ac.uk", 22)];
        let text = managed_config("icf", &hops, false, &link, &user_cfg).unwrap();
        assert!(text.contains("Host icfcc-icf\n"), "{text}");
        assert!(text.contains("    ProxyJump s1@gw.example:2222\n"), "{text}");
        assert!(text.find("Host icfcc-icf").unwrap() < text.find("Include").unwrap(), "our block comes first");
        let cfg = dir.join("managed");
        std::fs::write(&cfg, &text).unwrap();

        let ours = ssh_g(&cfg, "icfcc-icf");
        assert_eq!(g(&ours, "hostname"), Some("hastings.inf.ed.ac.uk"));
        assert_eq!(g(&ours, "user"), Some("s1234567"));
        assert_eq!(g(&ours, "controlmaster"), Some("false"));
        assert_eq!(g(&ours, "controlpath"), Some(link.to_str().unwrap()));
        assert_eq!(g(&ours, "proxyjump"), Some("s1@gw.example:2222"));
        let other = ssh_g(&cfg, "other");
        assert_eq!((g(&other, "hostname"), g(&other, "user")), (Some("other.example"), Some("bob")), "other hosts come from the user's config");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn managed_config_rejects_unsafe_values_and_omits_jumps_behind_a_proxy_command() {
        let p = Path::new("/tmp/x");
        assert!(managed_config("icf\nHost *", &[hop("u", "h.example", 22)], false, p, p).is_err());
        assert!(managed_config("icf", &[hop("u", "h.example\n  ProxyCommand x", 22)], false, p, p).is_err());
        assert!(managed_config("icf", &[hop("u", "h.example", 22)], false, Path::new("/tmp/a\"b"), p).is_err());
        let t = managed_config("icf", &[hop("u", "gw.example", 22), hop("u", "h.example", 22)], true, p, p).unwrap();
        assert!(!t.contains("ProxyJump"), "a ProxyCommand route is not rewritten as ProxyJump: {t}");
    }

    #[test]
    fn settings_key_is_added_and_removed_without_touching_other_keys() {
        let before = "{\n  \"editor.fontSize\": 13,\n  \"files.autoSave\": \"off\"\n}\n";
        let on = merge_key(Some(before), CONFIG_KEY, Some(serde_json::json!("/x/vscode_ssh_config"))).unwrap();
        let v: serde_json::Value = serde_json::from_str(&on).unwrap();
        assert_eq!(v[CONFIG_KEY], "/x/vscode_ssh_config");
        assert_eq!(v["editor.fontSize"], 13);
        assert!(on.find("editor.fontSize").unwrap() < on.find("files.autoSave").unwrap(), "order kept");
        let off = merge_key(Some(&on), CONFIG_KEY, None).unwrap();
        assert_eq!(serde_json::from_str::<serde_json::Value>(&off).unwrap(), serde_json::from_str::<serde_json::Value>(before).unwrap());
        assert!(merge_key(Some("{ // comment\n}"), CONFIG_KEY, None).is_err(), "JSONC is refused, never rewritten");
        assert!(merge_key(None, CONFIG_KEY, Some(serde_json::json!("/x"))).unwrap().contains(CONFIG_KEY));
    }
}
