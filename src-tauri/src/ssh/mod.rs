//! System OpenSSH integration. All processes are spawned with argv vectors (never a shell),
//! a cleared environment, and a generated config whose first block forces safe options
//! (strict host-key prompting, no forwarding) before including the user's own config.
//! The generated config is passed with `-F`, which OpenSSH propagates to ProxyJump hops.

pub mod askpass;
pub mod session;

